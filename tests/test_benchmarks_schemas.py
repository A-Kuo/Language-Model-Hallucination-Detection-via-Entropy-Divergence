"""Tests for benchmarks/schemas.py::AgentTraceRecord — the hash-derived
sample_id convention, mirroring data_generator.py::LabeledSample's."""

from benchmarks.schemas import AgentTraceRecord

_BASE_KWARGS = dict(
    is_answerable=True,
    has_context_available=True,
    action_sequence=["answer"],
    correct=True,
    groundedness=None,
    task_success=True,
    scores={"no_context": 0.1},
    latency_s=0.1,
)


def test_sample_id_autogenerated():
    r = AgentTraceRecord(query="What is 2+2?", final_answer="4", **_BASE_KWARGS)
    assert r.sample_id
    assert len(r.sample_id) == 12


def test_sample_id_stable_for_same_query_and_answer():
    r1 = AgentTraceRecord(query="Q", final_answer="A", **_BASE_KWARGS)
    r2 = AgentTraceRecord(query="Q", final_answer="A", **_BASE_KWARGS)
    assert r1.sample_id == r2.sample_id


def test_sample_id_differs_for_different_answer():
    r1 = AgentTraceRecord(query="Q", final_answer="A", **_BASE_KWARGS)
    r2 = AgentTraceRecord(query="Q", final_answer="B", **_BASE_KWARGS)
    assert r1.sample_id != r2.sample_id


def test_explicit_sample_id_not_overwritten():
    r = AgentTraceRecord(query="Q", final_answer="A", sample_id="custom-id", **_BASE_KWARGS)
    assert r.sample_id == "custom-id"
